/**
 * Симметричное двухсрезное нагельное соединение, СП 64 табл. 20.
 *
 * Балка — средний элемент толщиной c, накладки по бокам — крайние толщиной a.
 * Нагель работает в двух швах, и берётся наименьшее из трёх: смятие среднего
 * элемента, смятие крайних (на два шва) и изгиб самого нагеля (на два шва).
 *
 * @param {{d:number, plate:number, beam:number, mv?:number}} o мм, кроме mv
 */
export function dowelDouble({ d, plate, beam, mv = 1 }) {
  const dc = d / 10, a = plate / 10, c = beam / 10; // см
  const middle = 0.5 * c * dc;          // смятие среднего элемента, кН
  const edges = 2 * (0.8 * a * dc);     // смятие крайних, два шва
  const bend = 2 * (BEND_K.bolt * dc * dc); // изгиб стального нагеля, два шва
  const T = Math.min(middle, edges, bend) * mv * 1000; // Н
  const governs = middle <= edges && middle <= bend ? 'смятие балки'
    : edges <= bend ? 'смятие накладок' : 'изгиб нагеля';
  return { T, governs, middle: middle * mv * 1000, edges: edges * mv * 1000, bend: bend * mv * 1000 };
}

