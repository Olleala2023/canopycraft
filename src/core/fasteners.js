/** τ_fh по табл. 6.12, кПа, при глубине промерзания-оттаивания d_th, мм. */
export function heaveTau(stateId, dthMm) {
  const t = (HEAVE_STATES[stateId] ?? HEAVE_STATES.wet).tau;
  const d = HEAVE_DEPTHS;
  if (dthMm <= d[0]) return t[0];
  if (dthMm >= d[2]) return t[2];
  const i = dthMm <= d[1] ? 0 : 1;
  return t[i] + ((t[i + 1] - t[i]) * (dthMm - d[i])) / (d[i + 1] - d[i]);
}

