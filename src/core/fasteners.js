export const FROST_KH = 1.1;

/**
 * Глубина промерзания под навесом, мм.
 *
 * Карты нормативной глубины даются для суглинков и глин — это то, что человек
 * найдёт для своего места. На другой грунт пересчитываем отношением d₀: оно
 * точное, потому что √M_t у одного места общий.
 *
 * @param {number} dfnClay нормативная глубина для суглинков по карте, мм (0 — не задана)
 * @param {string} soilId ключ из SOILS
 */
export function frostDepth(dfnClay, soilId) {
  const soil = SOILS[soilId] ?? SOILS.clay;
  const dfn = (dfnClay * soil.d0) / SOILS.clay.d0;
  return { set: dfnClay > 0, soil, dfn, df: FROST_KH * dfn };
}

